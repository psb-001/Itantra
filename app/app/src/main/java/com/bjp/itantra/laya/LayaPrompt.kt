package com.bjp.itantra.laya

/**
 * The prompt the Laya decision head was trained on, as pure Kotlin: no Android classes, no ONNX
 * Runtime, nothing that needs a device. That is deliberate — the assembly is the one part of the
 * pipeline that can be wrong *silently*. A prompt built with the wrong special ids (say, the
 * BERT `[CLS]`/`[SEP]` ids instead of this model's) returns a perfectly uniform distribution
 * with no error raised anywhere, and a wrong marker position shifts which hidden state each
 * option is scored from without changing a single shape. `LayaPromptTest` therefore checks this
 * function's ids *and* marker positions against a fixture generated by the harness itself
 * (`eval/laya_mobile_assets.py --out-prompt-fixture`), for bench sentences, awkward whitespace,
 * and a state long enough to be truncated at the window edge.
 *
 * The format, identical to `LayaOnnx.build` in `eval/laya_onnx.py`:
 *
 *     <bos> question <eos> (<mask> option)* <eos> state <eos>
 *
 * One option is one `<mask>`, and the head reads the hidden state at each marker position; so the
 * marker count must equal the option count, and a prompt that lost a marker to truncation is not
 * a reading worth acting on. That is the only case where [build] returns null.
 */
object LayaPrompt {

    /**
     * Part of the model's training format, not a UI string: the classifier is zero-shot over the
     * message text, so the question is fixed and only the state changes language. Copied verbatim
     * from `eval/laya_onnx.py`.
     */
    const val QUESTION = "What kind of message is this?"

    val OPTIONS = listOf("routine message", "safety warning", "evacuation order", "medical emergency")

    /** Special ids the app reads from `assets/laya/config.json` at load time. */
    class Spec(val bos: Int, val eos: Int, val mask: Int, val maxLen: Int)

    class Prompt(val ids: IntArray, val markers: IntArray)

    /**
     * Assemble the prompt for [state]. Returns null when a marker would not survive the
     * [Spec.maxLen] window — with the prompt at the front that cannot happen for a window this
     * size, but returning null keeps the invariant local instead of trusting it.
     */
    fun build(
        bpe: LayaBpe,
        state: String,
        spec: Spec,
        question: String = QUESTION,
        options: List<String> = OPTIONS,
    ): Prompt? {
        val ids = ArrayList<Int>(64)
        ids.add(spec.bos)
        appendTokens(bpe, question, ids)
        ids.add(spec.eos)
        val markers = IntArray(options.size)
        for (i in options.indices) {
            markers[i] = ids.size
            ids.add(spec.mask)
            appendTokens(bpe, options[i], ids)
        }
        ids.add(spec.eos)
        appendTokens(bpe, state, ids)
        ids.add(spec.eos)

        // Truncation is the harness's too, and it drops only the tail of a very long message:
        // the question, the options, and their markers all sit at the front.
        val n = minOf(ids.size, spec.maxLen)
        for (m in markers) if (m >= n) return null
        return Prompt(IntArray(n) { ids[it] }, markers)
    }

    private fun appendTokens(bpe: LayaBpe, text: String, into: MutableList<Int>) {
        for (id in bpe.encode(text)) into.add(id)
    }
}
